package com.modserver.gametest;

import com.modserver.claim.Claim;
import com.modserver.claim.ClaimIndex;
import com.modserver.block.ModServerBlocks;
import com.modserver.nation.Nation;
import com.modserver.nation.NationManager;
import com.modserver.nation.NationRelation;
import com.modserver.nation.NationRole;
import net.minecraft.core.BlockPos;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestHelper;
import net.neoforged.neoforge.gametest.GameTestHolder;
import net.neoforged.neoforge.gametest.PrefixGameTestTemplate;

import java.util.UUID;

/**
 * Automated tests of the domain model (nations and claims).
 *
 * <p>They run without human intervention with: {@code ./gradlew runGameTestServer}
 * or {@code tools/gametest.sh}.</p>
 *
 * <p>The {@code empty} template is generated by the mod itself
 * ({@code tools/make_structure.py}) because Minecraft 1.21.1 does not include
 * GameTest templates in its jars.</p>
 */
@GameTestHolder("modserver")
@PrefixGameTestTemplate(false)
public class ModServerGameTests {

    /** The mod block must be registered and be different from air. */
    @GameTest(template = "empty")
    public void modBlockIsRegistered(GameTestHelper helper) {
        helper.assertTrue(ModServerBlocks.COG.isBound(), "The block was not registered");
        helper.assertFalse(ModServerBlocks.COG.get().defaultBlockState().isAir(), "The default block is air");
        helper.succeed();
    }

    /** Placing the block in the world must work and persist the state. */
    @GameTest(template = "empty")
    public void modBlockCanBePlaced(GameTestHelper helper) {
        helper.setBlock(1, 1, 1, ModServerBlocks.COG.get());
        helper.assertTrue(helper.getBlockState(new BlockPos(1, 1, 1)).is(ModServerBlocks.COG.get()),
                "The block was not placed correctly");
        helper.succeed();
    }

    /** One nation per player: the second attempt to create another must fail. */
    @GameTest(template = "empty")
    public void oneNationPerPlayer(GameTestHelper helper) {
        NationManager manager = new NationManager();
        UUID player = UUID.randomUUID();

        Nation nation = manager.create(UUID.randomUUID(), "Testland", player, 0x55FFFF, 0L);
        helper.assertTrue(manager.ownedBy(player).isPresent(), "The nation was not created");
        helper.assertTrue(manager.ownedBy(player).get().id().equals(nation.id()), "The nation is not the one of the player");
        helper.assertTrue(manager.count() == 1, "There must be exactly one nation");

        boolean rejected = false;
        try {
            manager.create(UUID.randomUUID(), "Otra", player, 0xFFFFFF, 0L);
        } catch (IllegalStateException e) {
            rejected = true;
        }
        helper.assertTrue(rejected, "A player must not be able to found two nations");

        helper.succeed();
    }

    /** Nation names are validated and are not repeated. */
    @GameTest(template = "empty")
    public void nationNamesAreValidated(GameTestHelper helper) {
        NationManager manager = new NationManager();
        helper.assertFalse(NationManager.isValidName("ab"), "A 2 character name is invalid");
        helper.assertFalse(NationManager.isValidName(""), "An empty name is invalid");
        helper.assertFalse(NationManager.isValidName("nombre con espacios"), "Spaces are not valid");
        helper.assertTrue(NationManager.isValidName("Nacion_1"), "Nacion_1 should be valid");

        manager.create(UUID.randomUUID(), "Nacion_1", UUID.randomUUID(), 0xFFFFFF, 0L);
        helper.assertTrue(manager.byName("nacion_1").isPresent(), "The search must ignore case");

        boolean rejected = false;
        try {
            manager.create(UUID.randomUUID(), "NACION_1", UUID.randomUUID(), 0xFFFFFF, 0L);
        } catch (IllegalArgumentException e) {
            rejected = true;
        }
        helper.assertTrue(rejected, "Names cannot be repeated ignoring case");

        helper.succeed();
    }

    /** A chunk can only belong to one nation at a time. */
    @GameTest(template = "empty")
    public void chunkCanOnlyBeClaimedOnce(GameTestHelper helper) {
        ClaimIndex index = new ClaimIndex();
        UUID first = UUID.randomUUID();
        UUID second = UUID.randomUUID();

        helper.assertTrue(index.isFree("minecraft:overworld", 5, -3), "The chunk should be free");
        helper.assertTrue(index.claim(new Claim("minecraft:overworld", 5, -3, first, 0L)),
                "The first claim should work");
        helper.assertFalse(index.claim(new Claim("minecraft:overworld", 5, -3, second, 0L)),
                "The second claim of the same chunk must fail");

        Claim stored = index.claimAt("minecraft:overworld", 5, -3);
        helper.assertTrue(stored != null && stored.nationId().equals(first),
                "The chunk must belong to the first nation");
        helper.assertTrue(index.chunkCount(first) == 1, "The first nation must have 1 chunk");
        helper.assertTrue(index.chunkCount(second) == 0, "The second nation must not have chunks");

        helper.assertTrue(index.release("minecraft:overworld", 5, -3) != null, "The chunk must be released");
        helper.assertTrue(index.isFree("minecraft:overworld", 5, -3), "The chunk is free again");

        helper.succeed();
    }

    /** The chunk key packs X and Z correctly (including negative values). */
    @GameTest(template = "empty")
    public void chunkKeyPacksCorrectly(GameTestHelper helper) {
        long key = Claim.pack(-120, 3400);
        helper.assertTrue(Claim.unpackX(key) == -120, "X must survive the packing");
        helper.assertTrue(Claim.unpackZ(key) == 3400, "Z must survive the packing");
        helper.assertTrue(Claim.unpackX(Claim.pack(0, 0)) == 0, "The origin must be 0,0");
        helper.succeed();
    }

    /** The nation survives the death of its owner: it is not dissolved nor does it change owner. */
    @GameTest(template = "empty")
    public void nationSurvivesOwnerDeath(GameTestHelper helper) {
        NationManager manager = new NationManager();
        UUID owner = UUID.randomUUID();
        Nation nation = manager.create(UUID.randomUUID(), "Eterna", owner, 0xFFFFFF, 0L);

        // "Death" of the owner: the nation is not touched, the player simply leaves.
        helper.assertTrue(manager.ownedBy(owner).isPresent(), "The nation must still exist");
        helper.assertTrue(manager.count() == 1, "No orphan nation must remain");
        helper.assertTrue(nation.owner().equals(owner), "The nation does not change owner on death");
        helper.assertTrue(nation.roleOf(owner) == NationRole.OWNER, "The owner keeps their role");
        helper.succeed();
    }

    /** Agreements between nations: the pact blocks the disputes. */
    @GameTest(template = "empty")
    public void agreementsBetweenNations(GameTestHelper helper) {
        NationManager manager = new NationManager();
        UUID a = UUID.randomUUID();
        UUID b = UUID.randomUUID();
        Nation first = manager.create(UUID.randomUUID(), "Alfa", a, 0xFF0000, 0L);
        Nation second = manager.create(UUID.randomUUID(), "Beta", b, 0x00FF00, 0L);

        helper.assertTrue(first.relationWith(second.id()) == NationRelation.NEUTRAL,
                "By default there is no agreement");

        first.setRelation(second.id(), NationRelation.PACT);
        helper.assertTrue(first.relationWith(second.id()).blocksDisputes(),
                "A pact must prevent disputes");
        helper.assertTrue(!first.relationWith(second.id()).blocksDisputes() == false,
                "The pact is still in force");

        first.setRelation(second.id(), NationRelation.WAR);
        helper.assertTrue(!first.relationWith(second.id()).blocksDisputes(),
                "At war chunks can be disputed");

        helper.succeed();
    }
}
