#!/usr/bin/env bash
# Control of the development server (NeoForge dev server, headless).
#
#   tools/server.sh start            starts the server (background)
#   tools/server.sh stop             stops the server
#   tools/server.sh restart          restarts
#   tools/server.sh status           status
#   tools/server.sh wait [seconds]   waits until the world is ready
#   tools/server.sh console "cmd"    sends a command (via RCON)
#   tools/server.sh logs [n]         last n lines of the log
#
# Remote control uses RCON (port 25575) because Gradle does not propagate stdin
# to the game process.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
modserver_check_toolchain

RUN_DIR="$MODSERVER_ROOT/run"
SERVER_LOG="$MODSERVER_LOG_DIR/server.log"
RCON_PORT="${MODSERVER_RCON_PORT:-25575}"
RCON_PASSWORD="${MODSERVER_RCON_PASSWORD:-modserver}"

is_running() {
  [ -f "$MODSERVER_PID_FILE" ] || return 1
  local pid
  pid="$(cat "$MODSERVER_PID_FILE" 2>/dev/null || true)"
  [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null
}

port_open() {
  (exec 3<>"/dev/tcp/$MODSERVER_HOST/$MODSERVER_PORT") 2>/dev/null && { exec 3<&- 3>&-; return 0; } || return 1
}

rcon() {
  python3 "$MODSERVER_ROOT/tools/rcon.py" --host "$MODSERVER_HOST" --port "$RCON_PORT" --password "$RCON_PASSWORD" "$@"
}

prepare_run_dir() {
  mkdir -p "$RUN_DIR"
  # EULA
  if [ ! -f "$RUN_DIR/eula.txt" ] || ! grep -q '^eula=true' "$RUN_DIR/eula.txt"; then
    printf 'eula=true\n' > "$RUN_DIR/eula.txt"
  fi
  # Test server configuration: offline (for bots), flat world (fast), RCON.
  if [ ! -f "$RUN_DIR/server.properties" ]; then
    cat > "$RUN_DIR/server.properties" <<PROPS
# Generated by tools/server.sh for the autonomous development loop
online-mode=false
level-type=minecraft\\:flat
level-name=devworld
spawn-protection=0
max-players=20
view-distance=6
simulation-distance=6
sync-chunk-writes=false
enable-command-block=true
allow-flight=true
gamemode=creative
motd=modServer dev
server-ip=$MODSERVER_HOST
server-port=$MODSERVER_PORT
enable-rcon=true
rcon.port=$RCON_PORT
rcon.password=$RCON_PASSWORD
broadcast-rcon-to-ops=true
PROPS
  fi
}

cmd_start() {
  if is_running; then
    echo "The server is already running (pid $(cat "$MODSERVER_PID_FILE"))."
    return 0
  fi
  prepare_run_dir
  mkdir -p "$MODSERVER_LOG_DIR"
  : > "$SERVER_LOG"
  (
    cd "$MODSERVER_ROOT"
    # setsid + --no-daemon: the server detaches from the shell session (and from
    # the Gradle daemon) so it survives the end of the task that launched it.
    setsid ./gradlew runServer --no-daemon --console=plain >> "$SERVER_LOG" 2>&1
    echo "EXIT_CODE=$?" >> "$SERVER_LOG"
  ) &
  local pid=$!
  echo "$pid" > "$MODSERVER_PID_FILE"
  echo "Server started (pid $pid). Log: $SERVER_LOG"
}

cmd_stop() {
  if is_running; then
    # "stop" via RCON: the server saves the world and closes cleanly.
    rcon stop >/dev/null 2>&1 || true
    local pid
    pid="$(cat "$MODSERVER_PID_FILE")"
    for _ in $(seq 1 60); do
      if ! kill -0 "$pid" 2>/dev/null; then
        echo "Server stopped."
        rm -f "$MODSERVER_PID_FILE"
        return 0
      fi
      sleep 1
    done
    echo "The server did not respond to stop; forcing shutdown." >&2
    kill -9 "$pid" 2>/dev/null || true
    rm -f "$MODSERVER_PID_FILE"
    return 1
  fi
  # Without a PID file: a development server may still be alive (for example, if
  # the task that launched it ended). If it is still running, the
  # run/devworld/session.lock prevents starting another server on the same world.
  for p in $(ps -eo pid,args | grep "[s]erverRunVmArgs" | awk '{print $1}'); do
    kill -9 "$p" 2>/dev/null || true
  done
  echo "The server is not running."
  rm -f "$MODSERVER_PID_FILE"
  return 0
}

cmd_wait() {
  local timeout="${1:-180}" waited=0
  while [ "$waited" -lt "$timeout" ]; do
    # Ready = the world has finished loading ("Done (x.xxxs)!") and the port answers.
    if grep -q 'Done (' "$SERVER_LOG" 2>/dev/null && port_open; then
      echo "Server ready at $MODSERVER_HOST:$MODSERVER_PORT (${waited}s)"
      return 0
    fi
    if ! is_running && [ "$waited" -gt 10 ]; then
      echo "ERROR: the server died during startup. Last lines:" >&2
      tail -40 "$SERVER_LOG" >&2 || true
      return 1
    fi
    sleep 2
    waited=$((waited + 2))
  done
  echo "ERROR: timeout while waiting for the server." >&2
  tail -40 "$SERVER_LOG" >&2 || true
  return 1
}

cmd_console() {
  if [ $# -lt 1 ]; then
    echo "Usage: tools/server.sh console \"<command>\"" >&2
    return 2
  fi
  if ! is_running; then
    echo "ERROR: the server is not running." >&2
    return 1
  fi
  rcon "$@"
}

cmd_status() {
  if is_running; then
    echo "Server: RUNNING (pid $(cat "$MODSERVER_PID_FILE"))"
  else
    echo "Server: STOPPED"
  fi
  if port_open; then
    echo "Port $MODSERVER_PORT: OPEN"
  else
    echo "Port $MODSERVER_PORT: CLOSED"
  fi
  if grep -q 'Done (' "$SERVER_LOG" 2>/dev/null; then
    echo "World: READY"
  else
    echo "World: loading or not started"
  fi
}

case "${1:-status}" in
  start)   cmd_start ;;
  stop)    cmd_stop ;;
  restart) cmd_stop || true; cmd_start; cmd_wait "${2:-180}" ;;
  status)  cmd_status ;;
  wait)    shift; cmd_wait "${1:-180}" ;;
  console) shift; cmd_console "$@" ;;
  logs)    tail -n "${1:-80}" "$SERVER_LOG" 2>/dev/null || echo "(no log)" ;;
  log-path) echo "$SERVER_LOG" ;;
  *)       echo "Commands: start|stop|restart|status|wait|console|logs|log-path" >&2; exit 2 ;;
esac
